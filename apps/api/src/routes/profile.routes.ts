import {
  auditLogPageSchema,
  auditLogQuerySchema,
  createInviteRequestSchema,
  createProfileRequestSchema,
  createdInviteSchema,
  cursorQuerySchema,
  inviteAcceptanceRequestSchema,
  invitePageSchema,
  inviteParamsSchema,
  memberPageSchema,
  memberParamsSchema,
  memberSchema,
  profileListQuerySchema,
  profilePageSchema,
  profileParamsSchema,
  profileSchema,
  replaceMemberRequestSchema,
  updateProfileRequestSchema,
} from '@medmap/shared';
import type { ProfileController } from '../controllers/profile.controller.js';
import { defineRoute } from '../utils/http.js';
import type { AnyRouteSpec } from '../utils/http.js';

export function profileRoutes(controller: ProfileController): AnyRouteSpec[] {
  return [
    defineRoute({
      method: 'get',
      path: '/profiles',
      summary: 'List profiles you own or were invited to',
      tag: 'Profiles',
      query: profileListQuerySchema,
      responses: { 200: { description: 'A page of profiles', schema: profilePageSchema } },
      handler: controller.list,
    }),
    defineRoute({
      method: 'post',
      path: '/profiles',
      summary: 'Create a profile',
      tag: 'Profiles',
      idempotent: true,
      body: createProfileRequestSchema,
      responses: { 201: { description: 'Profile created', schema: profileSchema } },
      handler: controller.create,
    }),
    defineRoute({
      method: 'get',
      path: '/profiles/:profileId',
      summary: 'Get a profile',
      tag: 'Profiles',
      params: profileParamsSchema,
      responses: { 200: { description: 'The profile', schema: profileSchema } },
      handler: controller.get,
    }),
    defineRoute({
      method: 'patch',
      path: '/profiles/:profileId',
      summary: 'Change a profile (owner)',
      tag: 'Profiles',
      ifMatch: true,
      params: profileParamsSchema,
      body: updateProfileRequestSchema,
      responses: { 200: { description: 'Updated profile', schema: profileSchema } },
      handler: controller.update,
    }),
    defineRoute({
      method: 'delete',
      path: '/profiles/:profileId',
      summary: 'Delete a profile and everything in it (owner)',
      tag: 'Profiles',
      params: profileParamsSchema,
      responses: { 204: { description: 'Deleted' } },
      handler: controller.remove,
    }),
    defineRoute({
      method: 'get',
      path: '/profiles/:profileId/members',
      summary: 'List people with access',
      tag: 'Sharing',
      params: profileParamsSchema,
      query: cursorQuerySchema,
      responses: { 200: { description: 'A page of members', schema: memberPageSchema } },
      handler: controller.listMembers,
    }),
    defineRoute({
      method: 'put',
      path: '/profiles/:profileId/members/:userId',
      summary: "Replace a member's role (owner)",
      tag: 'Sharing',
      ifMatch: true,
      params: memberParamsSchema,
      body: replaceMemberRequestSchema,
      responses: { 200: { description: 'Updated member', schema: memberSchema } },
      handler: controller.replaceMember,
    }),
    defineRoute({
      method: 'delete',
      path: '/profiles/:profileId/members/:userId',
      summary: 'Remove a member, or leave the profile',
      tag: 'Sharing',
      params: memberParamsSchema,
      responses: { 204: { description: 'Removed' } },
      handler: controller.removeMember,
    }),
    defineRoute({
      method: 'get',
      path: '/profiles/:profileId/invites',
      summary: 'List invites (owner)',
      tag: 'Sharing',
      params: profileParamsSchema,
      query: cursorQuerySchema,
      responses: { 200: { description: 'A page of invites', schema: invitePageSchema } },
      handler: controller.listInvites,
    }),
    defineRoute({
      method: 'post',
      path: '/profiles/:profileId/invites',
      summary: 'Invite someone by email (owner)',
      tag: 'Sharing',
      idempotent: true,
      params: profileParamsSchema,
      body: createInviteRequestSchema,
      responses: {
        201: {
          description: 'Invite created; the token is shown once',
          schema: createdInviteSchema,
        },
      },
      handler: controller.createInvite,
    }),
    defineRoute({
      method: 'delete',
      path: '/profiles/:profileId/invites/:inviteId',
      summary: 'Revoke an invite (owner)',
      tag: 'Sharing',
      params: inviteParamsSchema,
      responses: { 204: { description: 'Revoked' } },
      handler: controller.revokeInvite,
    }),
    defineRoute({
      method: 'post',
      path: '/invite-acceptances',
      summary: 'Accept an invite with its token',
      tag: 'Sharing',
      body: inviteAcceptanceRequestSchema,
      responses: { 201: { description: 'Membership created', schema: memberSchema } },
      handler: controller.acceptInvite,
    }),
    defineRoute({
      method: 'get',
      path: '/profiles/:profileId/audit-logs',
      summary: 'Audit log of a profile (owner)',
      tag: 'Profiles',
      params: profileParamsSchema,
      query: auditLogQuerySchema,
      responses: { 200: { description: 'A page of audit entries', schema: auditLogPageSchema } },
      handler: controller.listAuditLog,
    }),
  ];
}
